import argparse
from datetime import datetime

class AnalystAgent:
    def analyze(self, context, tone, recipient):
        print(f"[Analyst Agent] Analyzing: '{context}' for {recipient} with {tone} tone...")
        # Simple brief creation
        brief = {
            "purpose": context,
            "recipient": recipient,
            "tone": tone,
            "subject_hint": context[:40],
            "key_points": [context, f"Tone should be {tone}", f"Address to {recipient}"]
        }
        return brief

class WriterAgent:
    def write(self, brief):
        print(f"[Writer Agent] Drafting final email...")
        subject = f"Regarding: {brief['subject_hint']}"
        email = f"""Subject: {subject}

Dear {brief['recipient']},

I hope you are doing well.

I am writing to you regarding {brief['purpose'].lower()}. 

I would like to kindly request your understanding and support in this matter. Please let me know if you require any further information.

Thank you for your time and consideration.

Best regards,
[Your Name]
{datetime.now().strftime('%d %B %Y')}

---
Tone: {brief['tone']}
Generated by Email Drafting AI Agent | CrewAI Inspired Architecture
Context -> [Analyst Agent] -> Brief -> [Writer Agent] -> Final Email
"""
        return email

def draft_email(context, tone, recipient):
    analyst = AnalystAgent()
    writer = WriterAgent()
    
    brief = analyst.analyze(context, tone, recipient)
    final_email = writer.write(brief)
    
    print("\n" + "="*50)
    print("--- FINAL EMAIL GENERATED ---")
    print("="*50 + "\n")
    print(final_email)
    
    # Save to file for GitHub proof
    with open("output_email.txt", "w", encoding="utf-8") as f:
        f.write(final_email)
    print("\nSaved to output_email.txt")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="FREE Email Drafting AI Agent")
    parser.add_argument("--context", type=str, default="Requesting leave for 2 days due to family function")
    parser.add_argument("--tone", type=str, default="professional and polite")
    parser.add_argument("--recipient", type=str, default="my manager")
    args = parser.parse_args()

    draft_email(args.context, args.tone, args.recipient)